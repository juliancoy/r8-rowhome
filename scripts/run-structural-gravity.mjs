import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const outputDirectory = resolve("artifacts/structural-gravity");
mkdirSync(outputDirectory, { recursive: true });

writeFileSync(
  resolve(outputDirectory, "README.md"),
  [
    "# Structural Gravity Command Hook",
    "",
    "This command is reserved for structural gravity-load preprocessing and solver integration.",
    "The browser viewer does not run stiffness solves, member design, foundation design, or load combinations.",
    "",
    "Current model requirements for downstream preprocessing:",
    "- The rowhome model carries a conceptual `structural` schema.",
    "- The schema includes nodes, members, supports, materials, sections, load cases, and area loads.",
    "- The gravity report separates dead load, live load, roof load, and schematic wall dead load.",
    "- The CI report is generated by `tests/structural-gravity.test.ts` without importing the website renderer.",
    "",
    "Attach Frame3DD, OpenSees, a TypeScript direct-stiffness solver, or another validated solver here when selected."
  ].join("\n"),
  "utf8"
);

console.log(`Structural gravity command hook wrote ${outputDirectory}/README.md`);
