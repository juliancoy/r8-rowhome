import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { withTsModule } from "./lib/load-ts-module.mjs";

const outputDirectory = resolve("artifacts/plumbing-fluid");
mkdirSync(outputDirectory, { recursive: true });

writeFileSync(
  resolve(outputDirectory, "README.md"),
  [
    "# Plumbing Fluid-Analysis Command Hook",
    "",
    "This command is reserved for plumbing fluid-analysis preprocessing or solver integration.",
    "The browser viewer does not run plumbing fluid simulation, meshing, or report generation.",
    "",
    "Current model requirements for downstream preprocessing:",
    "- Plumbing pipes are generated as hollow pipe components.",
    "- Each pipe carries flow-node metadata on `object.userData.plumbing`.",
    "- Metadata includes `system`, `from`, `to`, `nominalDiameterIn`, `innerAreaSqFt`, `designFlowGpm`, `drainageFixtureUnits`, and `slopePercent`.",
    "- The CI report is generated by this artifact command before tests validate the same report shape."
  ].join("\n"),
  "utf8"
);

const reportDirectory = resolve("artifacts/plumbing-flow");
mkdirSync(reportDirectory, { recursive: true });
await withTsModule("/src/reports/plumbingFlow.ts", async ({ buildPlumbingFlowReport }) => {
  const report = buildPlumbingFlowReport();
  writeFileSync(resolve(reportDirectory, "plumbing-flow-report.json"), `${JSON.stringify(report, null, 2)}\n`, "utf8");
});

console.log(`Plumbing fluid-analysis command hook wrote ${outputDirectory}/README.md and ${reportDirectory}/plumbing-flow-report.json`);
