import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const outputDirectory = resolve("artifacts/hvac-fem");
mkdirSync(outputDirectory, { recursive: true });

writeFileSync(
  resolve(outputDirectory, "README.md"),
  [
    "# HVAC FEM/CFD Command Hook",
    "",
    "This command is the only project entry point reserved for HVAC thermofluid solving.",
    "The browser viewer does not run FEM, CFD, meshing, or solver work.",
    "",
    "Current model requirements for downstream preprocessing:",
    "- HVAC ducts are generated as hollow duct components.",
    "- Each duct carries flow-node metadata on `object.userData.hvac`.",
    "- Metadata includes `from`, `to`, `flowCfm`, `designVelocityFpm`, and `hydraulicAreaSqFt`.",
    "- The CI report is generated by `tests/hvac-flow-report.test.ts` without importing the website renderer.",
    "",
    "Attach a solver or mesh exporter here when a specific FEM/CFD toolchain is selected."
  ].join("\n"),
  "utf8"
);

console.log(`HVAC FEM command hook wrote ${outputDirectory}/README.md`);
