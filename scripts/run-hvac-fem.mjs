import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { withTsModule } from "./lib/load-ts-module.mjs";

const outputDirectory = resolve("artifacts/hvac-fem");
mkdirSync(outputDirectory, { recursive: true });

writeFileSync(
  resolve(outputDirectory, "README.md"),
  [
    "# HVAC FEM/CFD Command Hook",
    "",
    "This command is the only project entry point reserved for HVAC thermofluid solving.",
    "The browser viewer does not run FEM, CFD, meshing, or solver work.",
    "",
    "Current model requirements for downstream preprocessing:",
    "- HVAC ducts are generated as hollow duct components.",
    "- Each duct carries flow-node metadata on `object.userData.hvac`.",
    "- Metadata includes `from`, `to`, `flowCfm`, `designVelocityFpm`, and `hydraulicAreaSqFt`.",
    "- The CI report is generated by this artifact command before tests validate the same report shape.",
    "",
    "Attach a solver or mesh exporter here when a specific FEM/CFD toolchain is selected."
  ].join("\n"),
  "utf8"
);

const reportDirectory = resolve("artifacts/hvac-flow");
mkdirSync(reportDirectory, { recursive: true });
await withTsModule("/src/reports/hvacFlow.ts", async ({ buildHvacFlowReport }) => {
  const report = buildHvacFlowReport();
  writeFileSync(resolve(reportDirectory, "hvac-flow-report.json"), `${JSON.stringify(report, null, 2)}\n`, "utf8");
});

console.log(`HVAC FEM command hook wrote ${outputDirectory}/README.md and ${reportDirectory}/hvac-flow-report.json`);
