import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { relative, resolve, sep } from "node:path";

const root = resolve("sources");
const output = resolve("src/generated/documentIndex.ts");

function walk(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const fullPath = resolve(directory, entry.name);
      if (entry.isDirectory()) {
        return walk(fullPath);
      }
      if (!entry.isFile()) {
        return [];
      }
      const path = relative(root, fullPath).split(sep).join("/");
      return [{ path, sizeBytes: statSync(fullPath).size }];
    })
    .sort((a, b) => a.path.localeCompare(b.path));
}

const documents = walk(root);
mkdirSync(resolve("src/generated"), { recursive: true });
writeFileSync(
  output,
  `// Generated by scripts/generate-documents-index.mjs. Do not edit by hand.\n` +
    `export interface SourceDocumentEntry {\n` +
    `  path: string;\n` +
    `  sizeBytes: number;\n` +
    `}\n\n` +
    `export const sourceDocuments: SourceDocumentEntry[] = ${JSON.stringify(documents, null, 2)};\n`,
  "utf8"
);

console.log(`Indexed ${documents.length} source documents.`);

